import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.svm import SVC
from sklearn.metrics import (accuracy_score, balanced_accuracy_score,
                             recall_score, precision_score, f1_score,
                             confusion_matrix, log_loss)

file_name = 'NIR_SC_16ch_chromophore.xlsx'

# ------------------------------------------------------------
# 1. DATI + target binario (cancro = CBC/CEC/MEL)
# ------------------------------------------------------------
df = pd.read_excel(file_name, sheet_name='Base')
cm = pd.read_excel(file_name, sheet_name='channel_map')

wc_cols = [f'pixel_{i}_WC' for i in range(1, 17)]
wl = cm['centro_nm'].values

cancro = {'CBC', 'CEC', 'MEL'}
y = df['referenceValue'].apply(lambda c: 1 if c in cancro else 0).values

# ------------------------------------------------------------
# 2. PREPROCESSING SNV
#    SNV = (x - media) / deviazione_standard, per ogni campione
# ------------------------------------------------------------
X_raw = df[wc_cols].values
X = (X_raw - X_raw.mean(axis=1, keepdims=True)) / X_raw.std(axis=1, ddof=1, keepdims=True)

feat_names = [f'CH{i+1}_{wl[i]}nm' for i in range(16)]

# ------------------------------------------------------------
# 3. SPLIT stratificato 80/20
# ------------------------------------------------------------
X_tr, X_te, y_tr, y_te = train_test_split(
    X, y, test_size=0.20, stratify=y, random_state=42)

# ------------------------------------------------------------
# 4. SVM — Support Vector Machine
#    class_weight='balanced' gestisce in automatico lo sbilanciamento
#    probability=True calcola lo score Platt (necessario per la Log Loss)
# ------------------------------------------------------------
model = SVC(
    kernel='linear',
    C=1.0,
    class_weight='balanced',
    probability=True,
    random_state=42
)

model.fit(X_tr, y_tr)

# ------------------------------------------------------------
# 5. CURVE DI ADDESTRAMENTO
#    N.B.: L'SVM risolve un'ottimizzazione convessa globale (es. SMO).
#    Non procedendo per gradient boosting o epoche, non vi è una curva
#    di addestramento passo-passo da plottare in questo contesto.
# ------------------------------------------------------------

# ------------------------------------------------------------
# 6. METRICHE SUL TEST SET
# ------------------------------------------------------------
y_pred = model.predict(X_te)
y_prob = model.predict_proba(X_te)[:, 1]

print("=== METRICHE TEST SET ===")
print(f"Accuracy:          {accuracy_score(y_te, y_pred):.4f}")
print(f"Balanced Accuracy: {balanced_accuracy_score(y_te, y_pred):.4f}")
print(f"Recall (cancro):   {recall_score(y_te, y_pred):.4f}")
print(f"Precision:         {precision_score(y_te, y_pred):.4f}")
print(f"F1-score:          {f1_score(y_te, y_pred):.4f}")
print(f"Log Loss:          {log_loss(y_te, y_prob):.4f}")

cmx = confusion_matrix(y_te, y_pred)
print("\nMatrice di confusione:")
print(f"                 pred_NON   pred_CANCRO")
print(f"true_NON-cancro    {cmx[0,0]:3d}        {cmx[0,1]:3d}")
print(f"true_CANCRO        {cmx[1,0]:3d}        {cmx[1,1]:3d}")

# ------------------------------------------------------------
# 7. FEATURE IMPORTANCE (Coefficienti Iperpiano SVM)
#    Valido solo per kernel='linear'. Il modulo dei pesi indica l'importanza.
# ------------------------------------------------------------
imp = np.abs(model.coef_[0])
order = np.argsort(imp)

fig, ax = plt.subplots(figsize=(11, 5))
# Colora di rosso i canali con importanza spiccata (adatta la soglia se serve)
colors = ['#d1495b' if imp[i] > np.percentile(imp, 80) else '#457b9d' for i in order]
ax.barh([feat_names[i] for i in order], imp[order], color=colors)
ax.set_xlabel('Importanza Assoluta (Modulo dei Pesi SVM)')
ax.set_title('Feature importance — canali NIR (SVM Lineare)')
ax.grid(alpha=.3, axis='x')
plt.tight_layout(); plt.show()

print("\n=== RANKING FEATURE (SVM Lineare) ===")
for rank, i in enumerate(order[::-1], 1):
    print(f"  {rank:2d}. {feat_names[i]:16s}  peso_assoluto={imp[i]:.4f}")

# ------------------------------------------------------------
# 8. STRUTTURA DEL MODELLO (model info)
# ------------------------------------------------------------
print("\n=== STRUTTURA MODELLO ===")
print(f"Tipo: Support Vector Machine (SVC)")
print(f"Kernel: {model.kernel}")
print(f"Parametro di regolarizzazione (C): {model.C}")
print(f"Bilanciamento classi (class_weight): {model.class_weight}")
print(f"Numero totale di Support Vector: {len(model.support_vectors_)}")
print(f"  - SV per classe 0 (sano): {model.n_support_[0]}")
print(f"  - SV per classe 1 (cancro): {model.n_support_[1]}")

