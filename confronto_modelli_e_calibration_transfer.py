import pandas as pd #Prende i dati dai file Excel dei due sensori (Nibble e MicroNIR).
import numpy as np #Assegna a ciascun canale/pixel la relativa lunghezza d'onda in nanometri .
from scipy.interpolate import interp1d #Crea un vettore continuo common_grid, Servirà a far "dialogare" i due sensori sullo stesso asse x.
#Interpolazione Cubica: Poiché i due strumenti non leggono esattamente alle stesse lunghezze d'onda,
# la funzione stima i valori spettrali nei 50 punti della griglia comune
#Normalizza ogni singolo spettro (sottrae la media e divide per la deviazione standard)
#per eliminare differenze fisiche come variazioni di luce o altezza del campione.
#Prende la riga 1 del Nibble e la riga 1 del MicroNIR e ne calcola la correlazione R.
