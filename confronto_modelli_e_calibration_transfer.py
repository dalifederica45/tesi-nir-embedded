        r2_medio = np.mean(r2_list)
        info_persa = (1 - r2_medio) * 100

        print(f"\n--- RISULTATO FINALE ---")
        print(f"R^2 medio di ricostruzione: {r2_medio:.4f}")
        print(f"-> INFORMAZIONE PERSA: {info_persa:.2f}%")
