# ============================================================
df = pd.read_excel('dataset_ridotto.xlsx')
X_raw = df[[f'feature_{i+1}' for i in range(16)]].values

# Legenda yClass:
#   1=ACK benigna | 2=BCC maligna | 3=MEL maligna | 4=NEV benigna
#   5=SCC maligna | 6=SEK benigna | 7=OTHERS benigna
maligne = {2, 3, 5}   # BCC, MEL, SCC

y = np.array([1 if v in maligne else 0 for v in df['yClass'].values])

print("Distribuzione classi (0=benigna, 1=maligna):")
print(pd.Series(y).value_counts())

# --- SNV ---
X = (X_raw - X_raw.mean(axis=1, keepdims=True)) / (X_raw.std(axis=1, ddof=1, keepdims=True) + 1e-9)

# --- SPLIT stratificato ---
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, stratify=y, random_state=42
)
num_classes = 2

# ============================================================
# 1. TEACHER: XGBoost (binario)
# ============================================================
n_neg = np.sum(y_train == 0)
n_pos = np.sum(y_train == 1)
spw = n_neg / n_pos

teacher = xgb.XGBClassifier(
    n_estimators=100,
    max_depth=4,
    learning_rate=0.05,
    scale_pos_weight=spw,
    random_state=42,
    verbosity=0
)
teacher.fit(X_train, y_train)

y_pred_t = teacher.predict(X_test)
acc_t = accuracy_score(y_test, y_pred_t)
bacc_t = balanced_accuracy_score(y_test, y_pred_t)
print(f"\n[TEACHER XGBoost] Accuracy: {acc_t:.4f} | Balanced Acc: {bacc_t:.4f}")
print(f"[TEACHER] Recall(maligni): {recall_score(y_test, y_pred_t):.4f} | Precision: {precision_score(y_test, y_pred_t):.4f} | F1: {f1_score(y_test, y_pred_t):.4f}")

# ============================================================
# ============================================================
# 2. DISTILLATION: XGBoost -> 1D-CNN (binario) CON CLASS WEIGHTS
# ============================================================
from sklearn.utils.class_weight import compute_class_weight

TEMPERATURE = 3.0
ALPHA = 0.5   # ridotto: meno peso al teacher, più alle etichette vere

teacher_probs_train = teacher.predict_proba(X_train)

def softmax_temperature(probs, T):
    logits = np.log(np.clip(probs, 1e-9, 1.0))
    scaled = logits / T
    e = np.exp(scaled - scaled.max(axis=1, keepdims=True))
    return e / e.sum(axis=1, keepdims=True)

soft_labels_train = softmax_temperature(teacher_probs_train, TEMPERATURE)
y_train_onehot = tf.keras.utils.to_categorical(y_train, num_classes=num_classes)

X_train_cnn = X_train[..., np.newaxis]
X_test_cnn = X_test[..., np.newaxis]

# --- CALCOLO DEI PESI DI CLASSE (il fix per lo sbilanciamento) ---
cw = compute_class_weight('balanced', classes=np.array([0, 1]), y=y_train)
class_weight_dict = {0: cw[0], 1: cw[1]}
print(f"Pesi di classe: benigna={cw[0]:.2f}, maligna={cw[1]:.2f}")

# Vettore di peso per campione (serve perché usiamo una loss custom)
sample_weights = np.array([class_weight_dict[label] for label in y_train])

student = models.Sequential([
    Input(shape=(16, 1)),
    layers.Conv1D(32, 3, activation='relu', padding='same'),
    layers.BatchNormalization(),
    layers.Conv1D(64, 3, activation='relu', padding='same'),
    layers.MaxPooling1D(pool_size=2),
    layers.Flatten(),
    layers.Dense(64, activation='relu'),
    layers.Dropout(0.3),
    layers.Dense(num_classes, activation='softmax')
])

cce = tf.keras.losses.CategoricalCrossentropy()

def distillation_loss(y_true_and_soft, y_pred):
    y_true = y_true_and_soft[:, :num_classes]
    y_soft = y_true_and_soft[:, num_classes:]
    hard = cce(y_true, y_pred)
    soft = cce(y_soft, y_pred)
    return ALPHA * soft + (1.0 - ALPHA) * hard

y_combined = np.concatenate([y_train_onehot, soft_labels_train], axis=1)
student.compile(optimizer='adam', loss=distillation_loss, metrics=['accuracy'])

print("\nDistillazione in corso (con bilanciamento classi)...")
student.fit(X_train_cnn, y_combined, epochs=60, batch_size=16,
            sample_weight=sample_weights, verbose=0)
