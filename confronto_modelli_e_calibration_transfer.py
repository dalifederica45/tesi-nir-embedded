import pandas as pd
import numpy as np
import lightgbm as lgb
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.metrics import (accuracy_score, balanced_accuracy_score,
                             recall_score, precision_score, f1_score,
                             confusion_matrix, log_loss)

file_name = 'NIR_SC_16ch_chromophore.xlsx'

# ------------------------------------------------------------
# 1. DATI + target binario (cancro = CBC/CEC/MEL)
# ------------------------------------------------------------
df = pd.read_excel(file_name, sheet_name='Base')
cm = pd.read_excel(file_name, sheet_name='channel_map')

wc_cols = [f'pixel_{i}_WC' for i in range(1, 17)]
wl = cm['centro_nm'].values

cancro = {'CBC', 'CEC', 'MEL'}
y = df['referenceValue'].apply(lambda c: 1 if c in cancro else 0).values

# ------------------------------------------------------------
# 2. PREPROCESSING SNV (come nel paper Lossa et al.)
#    SNV = (x - media) / deviazione_standard, per ogni campione
# ------------------------------------------------------------
X_raw = df[wc_cols].values
X = (X_raw - X_raw.mean(axis=1, keepdims=True)) / X_raw.std(axis=1, ddof=1, keepdims=True)

feat_names = [f'CH{i+1}_{wl[i]}nm' for i in range(16)]

# ------------------------------------------------------------
# 3. SPLIT stratificato 80/20
# ------------------------------------------------------------
X_tr, X_te, y_tr, y_te = train_test_split(
    X, y, test_size=0.20, stratify=y, random_state=42)

# ------------------------------------------------------------
# 4. LIGHTGBM — alberi leaf-wise con gradient boosting
#    scale_pos_weight per lo sbilanciamento (511 vs 203)
#    importance_type='gain' per confrontabilità con XGBoost
# ------------------------------------------------------------
spw = (y_tr == 0).sum() / (y_tr == 1).sum()

model = lgb.LGBMClassifier(
    n_estimators=200,
    max_depth=4,
    learning_rate=0.05,
    subsample=0.8,
    colsample_bytree=0.8,
    scale_pos_weight=spw,
    importance_type='gain',
    random_state=42,
    verbose=-1 # Nasconde i warning interni
)

# Utilizzo dei callback per Early Stopping (API moderna di LightGBM)
callbacks = [
    lgb.early_stopping(stopping_rounds=20, verbose=False),
    lgb.log_evaluation(period=0)
]

model.fit(
    X_tr, y_tr,
    eval_set=[(X_tr, y_tr), (X_te, y_te)],
    eval_names=['Train', 'Test'],
    eval_metric=['binary_logloss', 'binary_error'],
    callbacks=callbacks
)

# ------------------------------------------------------------
# 5. CURVE DI ADDESTRAMENTO — accuracy e loss
# ------------------------------------------------------------
r = model.evals_result_
ep = range(len(r['Train']['binary_logloss']))

fig, (a1, a2) = plt.subplots(1, 2, figsize=(14, 5))
a1.plot(ep, r['Train']['binary_logloss'], label='Train', lw=2)
a1.plot(ep, r['Test']['binary_logloss'], label='Test', lw=2)
a1.axvline(model.best_iteration_, ls='--', color='gray', alpha=.6,
           label=f'early stop @ {model.best_iteration_}')
a1.set_xlabel('Iterazione'); a1.set_ylabel('Log Loss (Binary)')
a1.set_title('Curva di Loss (LightGBM)'); a1.legend(); a1.grid(alpha=.3)

# L'errore è 1 - accuracy
a2.plot(ep, [1-e for e in r['Train']['binary_error']], label='Train', lw=2)
a2.plot(ep, [1-e for e in r['Test']['binary_error']], label='Test', lw=2)
a2.axvline(model.best_iteration_, ls='--', color='gray', alpha=.6)
a2.set_xlabel('Iterazione'); a2.set_ylabel('Accuracy')
a2.set_title('Curva di Accuracy (LightGBM)'); a2.legend(); a2.grid(alpha=.3)
plt.tight_layout(); plt.show()

# ------------------------------------------------------------
