def esegui_analisi_ridondanza(file_path):
    print(f"--- Inizio analisi del file: {file_path} ---")

    # 1. CARICAMENTO
    try:
        # Leggiamo il foglio 'Base' dove risiedono i dati
        df = pd.read_excel(file_path, sheet_name='Base')
    except Exception as e:
        print(f"Errore nel caricamento: {e}")
        return

    # 2. SELEZIONE DATI (Escludiamo le colonne descrittive N, Sample, Class, yClass)
    # I dati spettrali iniziano dalla colonna 4 (indice 4)
    spectral_data = df.iloc[:, 4:]
    data = spectral_data.values
    n_samples, n_features_orig = data.shape
    n_features_target = 16

    print(f"Campioni caricati: {n_samples}")
    print(f"Feature originali: {n_features_orig}")

    # 3. SETUP ASSE SPETTRALE
    x_orig = np.linspace(0, 1, n_features_orig)
    x_target = np.linspace(0, 1, n_features_target)

    # 4. LOOP DI ANALISI (Downsampling -> Ricostruzione -> Valutazione)
    r2_list = []

    for i in range(n_samples):
        spec = data[i, :]

        # Pulizia: salto eventuali campioni con NaN
        if np.isnan(spec).any():
            continue

        # Downsampling: da 125 a 16
        f_down = interp1d(x_orig, spec, kind='cubic')
        spec_target = f_down(x_target)

        # Ricostruzione: da 16 a 125
        f_up = interp1d(x_target, spec_target, kind='cubic', fill_value="extrapolate")
        spec_reconstructed = f_up(x_orig)

        # Calcolo fedeltà
        r2_list.append(r2_score(spec, spec_reconstructed))

    # 5. RISULTATI
