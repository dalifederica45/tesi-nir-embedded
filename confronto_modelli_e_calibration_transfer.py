# --- 3. GRIGLIA COMUNE ---
common_grid = np.linspace(950, 1650, 50)

# --- 4. FUNZIONE DI ELABORAZIONE ---
def process_and_align(df, mapping, grid):
    cols = list(mapping.keys())
    data = df[cols].values
    sensor_nm = np.array([mapping[col] for col in cols])

    aligned_data = []
    for i in range(len(data)):#interp1d essendo che stiamo leggendo dati da sensori non uguali stima l'intensità del segnale
    #il tutto su una bestgrid comune
        f = interp1d(sensor_nm, data[i], kind='cubic', fill_value="extrapolate")
        interp_spec = f(grid)

        # Normalizzazione SNV
        mean = np.mean(interp_spec)
        std = np.std(interp_spec)
        snv_spec = (interp_spec - mean) / std if std != 0 else interp_spec - mean #mediante SNV Sottraendo la media e dividendo per la deviazione standard, rendi gli spettri indipendenti dalla quantità di luce riflessa o dalla distanza del campione.
        #Confronti solo la "forma" (la firma spettrale), eliminando le variazioni di intensità globale.
        aligned_data.append(snv_spec)

    return np.array(aligned_data)

# --- 5. ESECUZIONE ---
