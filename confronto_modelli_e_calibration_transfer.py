# 1. CARICAMENTO DEL DATASET
# Aggiornato con il nome e l'estensione corretta
file_name = 'NIR_SC_16ch_chromophore.xlsx'
df = pd.read_excel(file_name)

print("Colonne trovate nel dataset:", df.columns.tolist())

# 2. RICERCA AUTOMATICA DELLA COLONNA DIAGNOSI (TARGET)
nome_target = None
for col in df.columns:
    col_lower = str(col).strip().lower()
    if col_lower in ['class', 'classe', 'referencevalue', 'diagnosi', 'label']:
        nome_target = col
        break

if nome_target is None:
    print("\nERRORE CRITICO: Non trovo la colonna con le diagnosi (CBC, NEV, ecc.).")
    print("Controlla i nomi delle colonne stampati in alto.")
else:
    print(f"\n✅ Colonna diagnosi individuata in automatico: '{nome_target}'")

    # 3. PULIZIA DEI DATI
    y = df[nome_target]

    colonne_da_escludere = [nome_target]
    if 'sample' in df.columns:
        colonne_da_escludere.append('sample')

    X = df.drop(columns=colonne_da_escludere)

    # Teniamo solo le colonne puramente numeriche
    X = X.select_dtypes(include=[np.number])

    print(f"Forma originale: {X.shape[0]} pazienti, {X.shape[1]} variabili spettrali")
    print("\nConteggio pazienti per classe PRIMA del bilanciamento:")
    print(y.value_counts())

    # =======================================================
    # FASE 1: FEATURE SELECTION
    # =======================================================
    print("\n--- Avvio Riduzione Dimensionalità ---")

    k_features = 16
    if X.shape[1] <= k_features:
        print(f"Il dataset ha già {X.shape[1]} colonne dati. Salto il taglio a 16.")
        X_ridotto = X.values
        colonne_vincenti = X.columns
    else:
        selettore = SelectKBest(score_func=f_classif, k=k_features)
        X_ridotto = selettore.fit_transform(X, y)
        colonne_vincenti = X.columns[selettore.get_support()]
        print(f"Le 16 variabili spettrali PIÙ IMPORTANTI selezionate sono:\n{colonne_vincenti.tolist()}")

    # =======================================================
    # FASE 2: DATA AUGMENTATION (SMOTE)
    # =======================================================
    print("\n--- Avvio Data Augmentation (SMOTE) ---")
    smote = SMOTE(random_state=42)
    X_bilanciato, y_bilanciato = smote.fit_resample(X_ridotto, y)

    # =======================================================
    # FASE 3: CREAZIONE DEL NUOVO DATASET FINALE
    # =======================================================
    df_finale = pd.DataFrame(X_bilanciato, columns=colonne_vincenti)
    df_finale.insert(0, nome_target, y_bilanciato)

    print("\nConteggio pazienti per classe DOPO il bilanciamento:")
    print(df_finale[nome_target].value_counts())
    print(f"Forma finale del dataset: {df_finale.shape[0]} pazienti, {df_finale.shape[1] - 1} canali spettrali")

