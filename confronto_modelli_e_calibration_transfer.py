import pandas as pd
import numpy as np
import xgboost as xgb
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.metrics import (accuracy_score, balanced_accuracy_score,
                             recall_score, precision_score, f1_score,
                             confusion_matrix, log_loss)

file_name = 'NIR_SC_16ch_chromophore.xlsx'

# ------------------------------------------------------------
# 1. DATI + target binario (cancro = CBC/CEC/MEL)
# ------------------------------------------------------------
df = pd.read_excel(file_name, sheet_name='Base')
cm = pd.read_excel(file_name, sheet_name='channel_map')

wc_cols = [f'pixel_{i}_WC' for i in range(1, 17)]
wl = cm['centro_nm'].values

cancro = {'CBC', 'CEC', 'MEL'}
y = df['referenceValue'].apply(lambda c: 1 if c in cancro else 0).values

# ------------------------------------------------------------
# 2. PREPROCESSING SNV (come nel paper Lossa et al.)
#    SNV = (x - media) / deviazione_standard, per ogni campione
# ------------------------------------------------------------
X_raw = df[wc_cols].values
X = (X_raw - X_raw.mean(axis=1, keepdims=True)) / X_raw.std(axis=1, ddof=1, keepdims=True)

feat_names = [f'CH{i+1}_{wl[i]}nm' for i in range(16)]

# ------------------------------------------------------------
# 3. SPLIT stratificato 80/20
# ------------------------------------------------------------
X_tr, X_te, y_tr, y_te = train_test_split(
    X, y, test_size=0.20, stratify=y, random_state=42)

# ------------------------------------------------------------
# 4. XGBOOST — alberi di decisione con gradient boosting
#    scale_pos_weight per lo sbilanciamento (511 vs 203)
# ------------------------------------------------------------
spw = (y_tr == 0).sum() / (y_tr == 1).sum()

model = xgb.XGBClassifier(
    n_estimators=200,
    max_depth=4,
    learning_rate=0.05,
    subsample=0.8,
    colsample_bytree=0.8,
    scale_pos_weight=spw,
    eval_metric=['logloss', 'error'],
    early_stopping_rounds=20,
    random_state=42
)

model.fit(X_tr, y_tr,
          eval_set=[(X_tr, y_tr), (X_te, y_te)],
          verbose=False)

# ------------------------------------------------------------
# 5. CURVE DI ADDESTRAMENTO — accuracy e loss
# ------------------------------------------------------------
r = model.evals_result()
ep = range(len(r['validation_0']['logloss']))

fig, (a1, a2) = plt.subplots(1, 2, figsize=(14, 5))
a1.plot(ep, r['validation_0']['logloss'], label='Train', lw=2)
a1.plot(ep, r['validation_1']['logloss'], label='Test', lw=2)
a1.axvline(model.best_iteration, ls='--', color='gray', alpha=.6,
           label=f'early stop @ {model.best_iteration}')
a1.set_xlabel('Iterazione'); a1.set_ylabel('Log Loss')
a1.set_title('Curva di Loss'); a1.legend(); a1.grid(alpha=.3)

a2.plot(ep, [1-e for e in r['validation_0']['error']], label='Train', lw=2)
a2.plot(ep, [1-e for e in r['validation_1']['error']], label='Test', lw=2)
a2.axvline(model.best_iteration, ls='--', color='gray', alpha=.6)
a2.set_xlabel('Iterazione'); a2.set_ylabel('Accuracy')
a2.set_title('Curva di Accuracy'); a2.legend(); a2.grid(alpha=.3)
plt.tight_layout(); plt.show()

# ------------------------------------------------------------
# 6. METRICHE SUL TEST SET
# ------------------------------------------------------------
y_pred = model.predict(X_te)
y_prob = model.predict_proba(X_te)[:, 1]

print("=== METRICHE TEST SET ===")
print(f"Accuracy:          {accuracy_score(y_te, y_pred):.4f}")
print(f"Balanced Accuracy: {balanced_accuracy_score(y_te, y_pred):.4f}")
print(f"Recall (cancro):   {recall_score(y_te, y_pred):.4f}")
print(f"Precision:         {precision_score(y_te, y_pred):.4f}")
print(f"F1-score:          {f1_score(y_te, y_pred):.4f}")
print(f"Log Loss:          {log_loss(y_te, y_prob):.4f}")

cmx = confusion_matrix(y_te, y_pred)
print("\nMatrice di confusione:")
print(f"                 pred_NON   pred_CANCRO")
print(f"true_NON-cancro    {cmx[0,0]:3d}        {cmx[0,1]:3d}")
print(f"true_CANCRO        {cmx[1,0]:3d}        {cmx[1,1]:3d}")

# ------------------------------------------------------------
# 7. FEATURE IMPORTANCE — quale canale conta di più
# ------------------------------------------------------------
imp = model.feature_importances_
order = np.argsort(imp)

fig, ax = plt.subplots(figsize=(11, 5))
colors = ['#d1495b' if imp[i] > 0.09 else '#457b9d' for i in order]
ax.barh([feat_names[i] for i in order], imp[order], color=colors)
ax.set_xlabel('Importanza (gain)')
